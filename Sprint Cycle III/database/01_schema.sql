CREATE SCHEMA xpression;
SET search_path TO xpression, public;

CREATE TABLE account (
    account_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (btrim(name) <> ''),
    email text NOT NULL CHECK (email = lower(btrim(email)) AND email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'),
    role text NOT NULL CHECK (role IN ('creator','mentor','talent_scout','moderator','administrator')),
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active','suspended','banned','deactivated')),
    discipline text,
    open_to_commissions boolean NOT NULL DEFAULT false,
    password_hash text NOT NULL CHECK (btrim(password_hash) <> ''),
    bio text,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT account_email_key UNIQUE (email),
    CONSTRAINT account_id_role_key UNIQUE (account_id,role),
    CONSTRAINT account_commissions_creator CHECK (NOT open_to_commissions OR role = 'creator')
);

CREATE TABLE role_application (
    application_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    administrator_id bigint,
    administrator_role text GENERATED ALWAYS AS ('administrator'::text) STORED,
    applicant_name text NOT NULL CHECK (btrim(applicant_name) <> ''),
    email text NOT NULL CHECK (email = lower(btrim(email)) AND email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'),
    requested_role text NOT NULL CHECK (requested_role IN ('mentor','talent_scout')),
    statement text NOT NULL CHECK (btrim(statement) <> ''),
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','rejected')),
    submitted_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    decided_at timestamptz,
    approved_account_id bigint UNIQUE,
    CONSTRAINT application_admin_fk FOREIGN KEY (administrator_id,administrator_role) REFERENCES account(account_id,role),
    CONSTRAINT application_approved_role_fk FOREIGN KEY (approved_account_id,requested_role) REFERENCES account(account_id,role),
    CONSTRAINT application_decision_check CHECK (
      (status = 'pending' AND administrator_id IS NULL AND decided_at IS NULL AND approved_account_id IS NULL)
      OR (status = 'rejected' AND administrator_id IS NOT NULL AND decided_at IS NOT NULL AND approved_account_id IS NULL)
      OR (status = 'accepted' AND administrator_id IS NOT NULL AND decided_at IS NOT NULL AND approved_account_id IS NOT NULL)),
    CONSTRAINT application_dates_check CHECK (decided_at IS NULL OR decided_at >= submitted_at)
);

