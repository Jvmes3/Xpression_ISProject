-- Safe projection for presentation/public listings. This is not an authorization boundary.
CREATE VIEW public_work_feed AS
SELECT cw.work_id,cw.creator_id,a.name AS creator_name,cw.title,cw.media_type,cw.description,
       cw.soundcloud_url,cw.content_text,cw.published_at,
       EXISTS (SELECT 1 FROM nomination n WHERE n.work_id = cw.work_id AND n.status = 'approved') AS community_featured
FROM creative_work cw JOIN account a ON a.account_id = cw.creator_id
WHERE cw.visibility = 'available' AND NOT cw.archived AND a.status = 'active';

CREATE VIEW scout_creator_directory AS
SELECT a.account_id AS creator_id,a.name,a.discipline,a.open_to_commissions,a.bio,
       count(cw.work_id) AS visible_work_count
FROM account a LEFT JOIN creative_work cw
  ON cw.creator_id = a.account_id AND cw.visibility = 'available' AND NOT cw.archived
WHERE a.role = 'creator' AND a.status = 'active'
GROUP BY a.account_id,a.name,a.discipline,a.open_to_commissions,a.bio;

CREATE VIEW moderation_queue AS
SELECT mc.case_id,mc.report_id,mc.comment_report_id,mc.moderator_id,mc.status,
       coalesce(wr.reason,cr.reason) AS report_reason,wr.reason_type,
       coalesce(wr.reported_at,cr.reported_at) AS reported_at,
       coalesce(wr.work_id,c.work_id) AS work_id
FROM moderation_case mc
LEFT JOIN work_report wr ON wr.report_id = mc.report_id
LEFT JOIN comment_report cr ON cr.comment_report_id = mc.comment_report_id
LEFT JOIN comment c ON c.comment_id = cr.comment_id;

