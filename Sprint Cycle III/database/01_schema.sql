-- Cross-row integrity. These are integrity rules; they do not identify the signed-in user.
CREATE FUNCTION assert_specialized_approval(target_id bigint) RETURNS void
LANGUAGE plpgsql SET search_path = xpression, pg_temp AS $$
DECLARE a account%ROWTYPE;
BEGIN
    SELECT * INTO a FROM account WHERE account_id = target_id;
    IF FOUND AND a.role IN ('mentor','talent_scout') AND NOT EXISTS (
      SELECT 1 FROM role_application ra WHERE ra.approved_account_id = a.account_id
        AND ra.status = 'accepted' AND ra.requested_role = a.role AND ra.email = a.email) THEN
        RAISE EXCEPTION 'Specialized account % requires an accepted matching role application', target_id
          USING ERRCODE = '23514', CONSTRAINT = 'specialized_account_approval';
    END IF;
END;
$$;

CREATE FUNCTION check_specialized_approval() RETURNS trigger
LANGUAGE plpgsql SET search_path = xpression, pg_temp AS $$
BEGIN
    IF TG_TABLE_NAME = 'account' THEN
        PERFORM assert_specialized_approval(NEW.account_id);
    ELSE
        IF TG_OP <> 'INSERT' AND OLD.approved_account_id IS NOT NULL THEN
            PERFORM assert_specialized_approval(OLD.approved_account_id);
        END IF;
        IF TG_OP <> 'DELETE' AND NEW.approved_account_id IS NOT NULL THEN
            PERFORM assert_specialized_approval(NEW.approved_account_id);
        END IF;
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER account_specialized_approval
AFTER INSERT OR UPDATE ON account DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION check_specialized_approval();
CREATE CONSTRAINT TRIGGER application_specialized_approval
AFTER INSERT OR UPDATE OR DELETE ON role_application DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION check_specialized_approval();

CREATE FUNCTION check_feedback_request_accepted() RETURNS trigger
LANGUAGE plpgsql SET search_path = xpression, pg_temp AS $$
DECLARE request_status text;
BEGIN
    SELECT status INTO request_status FROM review_request WHERE request_id = NEW.request_id FOR SHARE;
    IF request_status IS DISTINCT FROM 'accepted' THEN
        RAISE EXCEPTION 'Feedback requires an accepted review request' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER feedback_requires_accepted_request BEFORE INSERT OR UPDATE ON mentor_feedback
FOR EACH ROW EXECUTE FUNCTION check_feedback_request_accepted();

CREATE FUNCTION protect_answered_request() RETURNS trigger
LANGUAGE plpgsql SET search_path = xpression, pg_temp AS $$
BEGIN
    IF NEW.status <> 'accepted' AND EXISTS (SELECT 1 FROM mentor_feedback WHERE request_id = OLD.request_id) THEN
        RAISE EXCEPTION 'A request with feedback must remain accepted' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER answered_request_remains_accepted BEFORE UPDATE OF status ON review_request
FOR EACH ROW EXECUTE FUNCTION protect_answered_request();

CREATE FUNCTION check_feedback_reply_owner() RETURNS trigger
LANGUAGE plpgsql SET search_path = xpression, pg_temp AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM mentor_feedback mf JOIN creative_work cw USING (work_id)
      WHERE mf.feedback_id = NEW.feedback_id AND cw.creator_id = NEW.creator_id) THEN
        RAISE EXCEPTION 'Only the reviewed work creator can be recorded as its reply author' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER reply_requires_work_owner BEFORE INSERT OR UPDATE ON feedback_reply
FOR EACH ROW EXECUTE FUNCTION check_feedback_reply_owner();

CREATE FUNCTION open_report_case() RETURNS trigger
LANGUAGE plpgsql SET search_path = xpression, pg_temp AS $$
BEGIN
    IF TG_TABLE_NAME = 'work_report' THEN
        INSERT INTO moderation_case(report_id,recorded_at) VALUES (NEW.report_id,NEW.reported_at);
    ELSE
        INSERT INTO moderation_case(comment_report_id,recorded_at) VALUES (NEW.comment_report_id,NEW.reported_at);
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER work_report_opens_case AFTER INSERT ON work_report
FOR EACH ROW EXECUTE FUNCTION open_report_case();
CREATE TRIGGER comment_report_opens_case AFTER INSERT ON comment_report
FOR EACH ROW EXECUTE FUNCTION open_report_case();

CREATE FUNCTION require_report_case() RETURNS trigger
LANGUAGE plpgsql SET search_path = xpression, pg_temp AS $$
BEGIN
    IF TG_TABLE_NAME = 'work_report' THEN
        IF EXISTS (SELECT 1 FROM work_report WHERE report_id = NEW.report_id) AND
          NOT EXISTS (SELECT 1 FROM moderation_case WHERE report_id = NEW.report_id) THEN
            RAISE EXCEPTION 'Every work report requires exactly one moderation case' USING ERRCODE = '23514';
        END IF;
    ELSIF TG_TABLE_NAME = 'comment_report' THEN
        IF EXISTS (SELECT 1 FROM comment_report WHERE comment_report_id = NEW.comment_report_id) AND
          NOT EXISTS (SELECT 1 FROM moderation_case WHERE comment_report_id = NEW.comment_report_id) THEN
            RAISE EXCEPTION 'Every comment report requires exactly one moderation case' USING ERRCODE = '23514';
        END IF;
    ELSE
        IF OLD.report_id IS NOT NULL AND EXISTS (SELECT 1 FROM work_report WHERE report_id = OLD.report_id) AND
          NOT EXISTS (SELECT 1 FROM moderation_case WHERE report_id = OLD.report_id) THEN
            RAISE EXCEPTION 'A work report cannot lose its moderation case' USING ERRCODE = '23514';
        END IF;
        IF OLD.comment_report_id IS NOT NULL AND EXISTS (SELECT 1 FROM comment_report WHERE comment_report_id = OLD.comment_report_id) AND
          NOT EXISTS (SELECT 1 FROM moderation_case WHERE comment_report_id = OLD.comment_report_id) THEN
            RAISE EXCEPTION 'A comment report cannot lose its moderation case' USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER work_report_requires_case AFTER INSERT OR UPDATE ON work_report
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION require_report_case();
CREATE CONSTRAINT TRIGGER comment_report_requires_case AFTER INSERT OR UPDATE ON comment_report
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION require_report_case();
CREATE CONSTRAINT TRIGGER moderation_case_cannot_orphan_report AFTER UPDATE OR DELETE ON moderation_case
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION require_report_case();

CREATE FUNCTION apply_moderation_decision() RETURNS trigger
LANGUAGE plpgsql SET search_path = xpression, pg_temp AS $$
DECLARE new_visibility text;
BEGIN
    IF NEW.status = 'closed' THEN
        new_visibility := CASE WHEN NEW.action_taken = 'kept_available' THEN 'available' ELSE NEW.action_taken END;
        IF NEW.report_id IS NOT NULL THEN
            UPDATE creative_work SET visibility = new_visibility
              WHERE work_id = (SELECT work_id FROM work_report WHERE report_id = NEW.report_id);
        ELSE
            UPDATE comment SET visibility = new_visibility
              WHERE comment_id = (SELECT comment_id FROM comment_report WHERE comment_report_id = NEW.comment_report_id);
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER closed_case_applies_visibility AFTER INSERT OR UPDATE ON moderation_case
FOR EACH ROW EXECUTE FUNCTION apply_moderation_decision();

CREATE FUNCTION protect_account_status() RETURNS trigger
LANGUAGE plpgsql SET search_path = xpression, pg_temp AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'active' THEN
            RAISE EXCEPTION 'New accounts start active; insert a status_change for later actions' USING ERRCODE = '23514';
        END IF;
    ELSIF NEW.status IS DISTINCT FROM OLD.status AND pg_trigger_depth() < 2 THEN
        RAISE EXCEPTION 'Change status by inserting status_change; direct status updates are not allowed' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER account_status_requires_audit BEFORE INSERT OR UPDATE OF status ON account
FOR EACH ROW EXECUTE FUNCTION protect_account_status();

CREATE FUNCTION apply_status_change() RETURNS trigger
LANGUAGE plpgsql SET search_path = xpression, pg_temp AS $$
DECLARE previous_status text;
BEGIN
    SELECT status INTO previous_status FROM account WHERE account_id = NEW.account_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Target account does not exist' USING ERRCODE = '23503'; END IF;
    IF NEW.new_status = previous_status THEN
        RAISE EXCEPTION 'New status must differ from the existing status' USING ERRCODE = '23514';
    END IF;
    NEW.old_status := previous_status;
    UPDATE account SET status = NEW.new_status WHERE account_id = NEW.account_id;
    RETURN NEW;
END;
$$;
CREATE TRIGGER status_change_updates_account BEFORE INSERT ON status_change
FOR EACH ROW EXECUTE FUNCTION apply_status_change();

CREATE FUNCTION reject_audit_mutation() RETURNS trigger
LANGUAGE plpgsql SET search_path = xpression, pg_temp AS $$
BEGIN
    RAISE EXCEPTION 'Status change history is append-only' USING ERRCODE = '23514';
END;
$$;
CREATE TRIGGER status_history_append_only BEFORE UPDATE OR DELETE ON status_change
FOR EACH ROW EXECUTE FUNCTION reject_audit_mutation();

